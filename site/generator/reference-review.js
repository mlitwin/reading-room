#!/usr/bin/env node
// Generate the Reference Grammar editorial review checklist,
// site/latin/reference-grammar-review.md (Plans/latin-text-centered-reader-plan.md, A6).
//
// One checkbox per chapter, with what a proofreader needs for it: § range, page
// link, edited sections (and their edit notes), this site's additions, and any
// warning-level invariant findings. Regenerating keeps the ticks already made
// (matched by chapter id), so the file doubles as the review log.
//
//   npm run reference:review

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { indexReferenceGrammar, sectionLabel } from './lib/reference-grammar.js';
import { rangeLabel } from './build-reference-grammar.js';
import { runSuite } from './validate/runner.js';
import { referenceGrammarInvariants } from './validate/reference-grammar.invariants.js';

const here = dirname(fileURLToPath(import.meta.url));
const REPO = join(here, '..', '..');
const REF = join(REPO, 'content', '_language', 'latin', 'reference-grammar.json');
export const REVIEW = join(REPO, 'site', 'latin', 'reference-grammar-review.md');
const SITE = 'https://antoninus.org/reading-room/_language/latin/reference/';

/** Chapter ids already ticked in an existing review file. */
export function tickedChapters(md) {
  return new Set([...String(md).matchAll(/^- \[x\] .*?<!-- (ch-[a-z0-9-]+) -->/gm)].map((m) => m[1]));
}

export function renderReview(ref, ticked = new Set()) {
  const index = indexReferenceGrammar(ref);
  const report = runSuite('reference', referenceGrammarInvariants, ref);
  const warnings = report.invariants.filter((i) => !i.passed && i.severity === 'warning');
  const chapterOf = (path) => {
    const m = path.match(/chapters\["(ch-[^"]+)"\]/) || path.match(/sections\["([^"]+)"\]/);
    if (!m) return null;
    return m[1].startsWith('ch-') ? m[1] : index.sections.get(m[1])?.chapter.id ?? null;
  };

  const lines = [
    '# Reference Grammar review',
    '',
    'Generated by `npm run reference:review` (site/generator/reference-review.js).',
    'Proofread each chapter against the page, fix `content/_language/latin/reference-grammar.json`,',
    'then tick it. Regenerating keeps ticks. Seed-time heading changes are in',
    '[reference-grammar-seed-report.md](reference-grammar-seed-report.md).',
    '',
  ];
  const total = index.chapters.length;
  const done = index.chapters.filter((c) => ticked.has(c.id)).length;
  lines.push(`**${done} / ${total} chapters reviewed.**`, '');

  for (const part of index.parts) {
    lines.push(`## ${part.label}`, '');
    for (const ch of part.chapters) {
      const tick = ticked.has(ch.id) ? 'x' : ' ';
      const range = rangeLabel(ch);
      lines.push(`- [${tick}] [${ch.label}](${SITE}${ch.slug}.html)${range ? ` — ${range}` : ''} (${ch.sectionIds.length} section${ch.sectionIds.length === 1 ? "" : "s"}) <!-- ${ch.id} -->`);
      for (const id of ch.sectionIds) {
        const info = index.sections.get(id);
        if (!info) continue;
        if (info.source === 'editorial') lines.push(`  - addition: ${info.heading} (\`${id}\`)`);
        else if (info.edited) lines.push(`  - edited ${sectionLabel(info)}: ${ref.sections[id].edit_note ?? '_no edit_note_'}`);
      }
      for (const w of warnings) {
        for (const v of w.violations) {
          if (chapterOf(v.path) === ch.id) lines.push(`  - ⚠ ${w.id}: ${v.message}`);
        }
      }
    }
    lines.push('');
  }
  const loose = warnings.flatMap((w) => w.violations.filter((v) => !chapterOf(v.path)).map((v) => `- ⚠ ${w.id}: ${v.path} ${v.message}`));
  if (loose.length) lines.push('## Document-level warnings', '', ...loose, '');
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const ref = JSON.parse(await readFile(REF, 'utf8'));
  let prior = '';
  try { prior = await readFile(REVIEW, 'utf8'); } catch (e) { if (e.code !== 'ENOENT') throw e; }
  const md = renderReview(ref, tickedChapters(prior));
  await writeFile(REVIEW, md);
  console.log(`reference review → ${REVIEW}`);
}
